/// Arquivo extra de um modelo com visão: o `mmproj` (torre de imagem + conector), baixado junto e conferido por SHA-256.
/// Fica ao lado do modelo como `<nome do modelo sem .gguf>.mmproj.gguf` (é onde o motor próprio o procura).
pub struct MmprojFile {
    /// `id` da entrada do catálogo a que pertence
    pub model_id: &'static str,
    pub url: &'static str,
    pub size: u64,
    pub sha256: &'static str,
}

/// Tamanhos e SHA-256 lidos dos cabeçalhos do Hugging Face (X-Linked-Size / X-Linked-ETag) em 23/11/2026.
pub const MMPROJ: &[MmprojFile] = &[MmprojFile {
    model_id: "smolvlm-500m",
    url: "https://huggingface.co/ggml-org/SmolVLM-500M-Instruct-GGUF/resolve/main/mmproj-SmolVLM-500M-Instruct-f16.gguf",
    size: 199_468_800,
    sha256: "4b2fca922e549e9b9608f4ba56f93565dd5220e935ba5570a2a864a0fcc988a6",
}];

pub fn mmproj_for(model_id: &str) -> Option<&'static MmprojFile> {
    MMPROJ.iter().find(|m| m.model_id == model_id)
}

/// Nome local do mmproj de uma entrada: `<arquivo do modelo sem .gguf>.mmproj.gguf`.
pub fn mmproj_file(e: &CatalogEntry) -> String {
    format!("{}.mmproj.gguf", e.file.strip_suffix(".gguf").unwrap_or(e.file))
}

pub fn find(id: &str) -> Option<&'static CatalogEntry> {
    CATALOG.iter().find(|e| e.id == id)
}
