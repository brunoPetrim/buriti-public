pub struct CatalogEntry {
    pub id: &'static str,
    pub name: &'static str,
    pub desc: &'static str,
    pub file: &'static str,
    pub url: &'static str,
    pub size: u64,
    pub sha256: &'static str,
    pub min_ram_gb: u32,
    /// o motor próprio do Buriti já sabe rodar este modelo (hoje: arquiteturas Qwen2 e Llama 3.x)
    pub native: bool,
    // Metadados neutros de idioma (fonte: model card oficial; conferidos em 22/11/2026).
    /// organização que desenvolveu o modelo
    pub provider: &'static str,
    /// mês de lançamento "AAAA-MM"
    pub released: &'static str,
    /// número de parâmetros, como no model card (ex.: "1.54B")
    pub params: &'static str,
    /// contexto máximo nativo em milhares de tokens
    pub ctx_k: u32,
    pub license: &'static str,
    /// a licença só permite pesquisa/avaliação (uso comercial exige pedir licença ao autor)
    pub non_commercial: bool,
    /// idiomas: "29+", "100+", "8" (oficialmente suportados)
    pub langs: &'static str,
    /// o modelo rende bem melhor em ingles: o chat avisa (independe do idioma da interface)
    pub english_best: bool,
    /// tem modo de raciocínio (<think>)
    pub thinking: bool,
    /// modelo voltado a programação: nunca é o "recomendado para o seu PC" na interface
    pub coding: bool,
}

